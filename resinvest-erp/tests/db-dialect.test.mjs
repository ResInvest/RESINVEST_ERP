/* Warstwa bazy: tłumaczenie poleceń SQLite → PostgreSQL, zgodność interfejsu z node:sqlite, konfiguracja. */
import { test, before, after } from "node:test";
import assert from "node:assert/strict";
import { DatabaseSync } from "node:sqlite";
import { toPg, PgDb } from "../server/db/postgres.mjs";
import { databaseConfig } from "../server/db/index.mjs";
import { TABLES, PG_DDL, SQLITE_DDL } from "../server/db/schema.mjs";
import { pgAvailable, createDb, dropAll } from "./support/helpers.mjs";

const HAVE_PG = await pgAvailable();
const skip = HAVE_PG ? false : "brak RIW_TEST_PG_URL — testy PostgreSQL pominięte";
let db;
before(async () => { if (HAVE_PG) { const d = await createDb("dialect"); db = new PgDb(d.cfg); db.ensureSchema(); } });
after(async () => { if (db) db.close(); await dropAll(); });

test("toPg: parametry, aliasy, INSERT OR IGNORE, BEGIN IMMEDIATE, RETURNING", () => {
  assert.equal(toPg("SELECT * FROM accounts WHERE user_id = ?").text, "SELECT * FROM accounts WHERE user_id = $1");
  assert.equal(toPg("UPDATE t SET a = ?, b = ? WHERE c = ?").params, 3);
  assert.equal(toPg("SELECT '?' AS q, x FROM t WHERE y = ?").text, "SELECT '?' AS q, x FROM t WHERE y = $1");
  assert.equal(toPg("SELECT 'it''s ?' AS q WHERE a = ?").text, "SELECT 'it''s ?' AS q WHERE a = $1");
  assert.equal(toPg("BEGIN IMMEDIATE").text, "BEGIN");
  assert.ok(toPg("BEGIN IMMEDIATE").begin && toPg("COMMIT").end && toPg("ROLLBACK").end);
  assert.equal(toPg("INSERT OR IGNORE INTO meta(key, value) VALUES ('created_at', ?)").text, "INSERT INTO meta(key, value) VALUES ('created_at', $1) ON CONFLICT DO NOTHING");
  assert.match(toPg('SELECT user_id AS userId, to_addr AS "to", next_at AS nextAt, COUNT(*) AS n FROM outbox').text, /AS "userId", to_addr AS "to", next_at AS "nextAt", COUNT\(\*\) AS n/);
  assert.equal(toPg("CREATE TABLE x(seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)").text, "CREATE TABLE x(seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)", "słowo kluczowe to nie alias");
  assert.match(toPg("INSERT INTO outbox(ts) VALUES (?)").text, / RETURNING id$/);
  assert.match(toPg("INSERT INTO journal(ts) VALUES (?)").text, / RETURNING seq$/);
  assert.doesNotMatch(toPg("INSERT INTO sessions(token_hash) VALUES (?)").text, /RETURNING/);
  assert.equal(toPg("SELECT rev FROM state WHERE id = 1 FOR UPDATE").readOnly, false);
  assert.equal(toPg("SELECT 1 FROM accounts LIMIT 1").readOnly, true);
});

test("schemat: te same tabele i kolumny w SQLite, PostgreSQL i opisie przenoszenia", () => {
  const pgTables = PG_DDL.filter(s => /^CREATE TABLE/.test(s)).map(s => /EXISTS (\w+)\(/.exec(s)[1]).sort();
  const liteTables = [...SQLITE_DDL.matchAll(/CREATE TABLE IF NOT EXISTS (\w+)\(/g)].map(m => m[1]).sort();
  assert.deepEqual(pgTables, liteTables);
  assert.deepEqual(TABLES.map(t => t.name).sort(), liteTables);
  for (const t of TABLES) {
    const ddl = PG_DDL.find(s => s.startsWith(`CREATE TABLE IF NOT EXISTS ${t.name}(`));
    for (const [c] of t.cols) assert.match(ddl, new RegExp(`[(, ]${c} `), `${t.name}.${c}`);
  }
});

test("konfiguracja: domyślnie SQLite; PostgreSQL z adresu lub pól; błędy bez ujawniania hasła", () => {
  assert.deepEqual(databaseConfig({}), { driver: "sqlite" });
  assert.deepEqual(databaseConfig({ DATABASE_URL: "postgres://u:p@h/db" }), { driver: "sqlite" }, "sam adres nie przełącza silnika — wymagane DB_DRIVER=postgres");
  const a = databaseConfig({ DB_DRIVER: "postgres", DATABASE_URL: "postgres://u:tajne@h:5433/db" });
  assert.equal(a.driver, "postgres"); assert.equal(a.client.connectionString, "postgres://u:tajne@h:5433/db");
  const b = databaseConfig({ DB_DRIVER: "postgres", DB_HOST: "10.0.0.5", DB_PORT: "5433", DB_NAME: "erp", DB_USER: "riw", DB_PASSWORD: "p@ss:/#word", DB_SSL: "require", DB_SCHEMA: "erp" });
  assert.deepEqual([b.client.host, b.client.port, b.client.database, b.client.user, b.client.password, b.schema], ["10.0.0.5", 5433, "erp", "riw", "p@ss:/#word", "erp"]);
  assert.deepEqual(b.client.ssl, { rejectUnauthorized: false });
  assert.throws(() => databaseConfig({ DB_DRIVER: "oracle" }), /nieznany silnik/);
  assert.throws(() => databaseConfig({ DB_DRIVER: "postgres" }), /DATABASE_URL albo DB_HOST/);
  assert.throws(() => databaseConfig({ DB_DRIVER: "postgres", DB_NAME: "a", DB_USER: "b", DB_SSL: "maybe" }), /DB_SSL/);
  assert.throws(() => databaseConfig({ DB_DRIVER: "postgres", DB_NAME: "a", DB_USER: "b", DB_SCHEMA: "x; DROP" }), /DB_SCHEMA/);
});

test("interfejs jak node:sqlite: get / all / run / iterate, typy i znaki", { skip }, () => {
  const ins = db.prepare("INSERT INTO outbox(ts, template, to_addr, user_id, status, kind, subject, body, attempts, next_at, notice_id, updated_at) VALUES (?, ?, ?, ?, 'QUEUED', ?, ?, ?, 0, ?, ?, ?)");
  const text = "Zażółć gęślą jaźń — 'apostrof' \"cudzysłów\" \\ ukośnik; -- komentarz 🌲   " + "x".repeat(70000);
  const r1 = ins.run("2026-11-09T08:00:00.000Z", "notice", "a@b.pl", null, "notice", "Temat", text, "2026-11-09T08:00:00.000Z", undefined, "2026-11-09T08:00:00.000Z");
  const r2 = ins.run("2026-11-09T08:00:01.000Z", "notice", "c@d.pl", "u1", "notice", "", "{}", null, "n1", "x");
  assert.equal(r1.changes, 1); assert.equal(typeof r1.lastInsertRowid, "number"); assert.equal(r2.lastInsertRowid, r1.lastInsertRowid + 1);
  const row = db.prepare("SELECT id, body, user_id AS userId, attempts, body IS NOT NULL AS retryable FROM outbox WHERE id = ?").get(r1.lastInsertRowid);
  assert.equal(row.body, text); assert.equal(row.userId, null); assert.strictEqual(row.attempts, 0); assert.equal(!!row.retryable, true);
  assert.equal(db.prepare("SELECT 1 AS x FROM outbox WHERE id = ?").get(-5), undefined, "brak wiersza → undefined");
  assert.strictEqual(db.prepare("SELECT COUNT(*) AS n FROM outbox").get().n, 2, "COUNT jako liczba JS");
  assert.deepEqual(db.prepare("SELECT to_addr AS \"to\" FROM outbox ORDER BY id DESC LIMIT ?").all(5).map(r => r.to), ["c@d.pl", "a@b.pl"]);
  assert.equal([...db.prepare("SELECT id FROM outbox ORDER BY id").iterate()].length, 2);
  assert.equal(db.prepare("UPDATE outbox SET status = 'SENT' WHERE status = ?").run("QUEUED").changes, 2);
  assert.equal(db.prepare("DELETE FROM outbox WHERE id = ?").run(-1).changes, 0);
  assert.throws(() => db.prepare("SELECT 1 AS x FROM outbox WHERE id = ?").get(), /Liczba parametrów/);
});

test("liczby: REAL (kolejność rekordów) i BIGINT (rewizje) bez utraty precyzji", { skip }, () => {
  const up = db.prepare("INSERT INTO rows(coll, id, ord, json, sha) VALUES (?, ?, ?, ?, ?) ON CONFLICT(coll, id) DO UPDATE SET ord = excluded.ord, json = excluded.json, sha = excluded.sha");
  const ords = [0, 1, 1.5, 0.1 + 0.2, 1e-7, 123456.000001, -3.25, 2 ** 40 + 0.5];
  ords.forEach((o, i) => up.run("t", "id" + i, o, "{}", "s"));
  const back = db.prepare("SELECT id, ord FROM rows WHERE coll = ? ORDER BY id").all("t").map(r => r.ord);
  assert.deepEqual(back, ords);
  db.prepare("INSERT INTO state(id, rev, schema, json, sha256, updated_at) VALUES (1, ?, ?, ?, ?, ?)").run(9007199254740991, 9, "{}", "x", "t");
  assert.strictEqual(db.prepare("SELECT rev FROM state WHERE id = 1").get().rev, 9007199254740991);
  db.exec("DELETE FROM state"); db.exec("DELETE FROM rows");
});

test("transakcja: ROLLBACK wycofuje wszystko, COMMIT zapisuje", { skip }, () => {
  db.exec("BEGIN IMMEDIATE");
  db.prepare("INSERT INTO meta(key, value) VALUES (?, ?)").run("tx-test", "1");
  db.exec("ROLLBACK");
  assert.equal(db.prepare("SELECT value FROM meta WHERE key = ?").get("tx-test"), undefined);
  db.exec("BEGIN IMMEDIATE");
  db.prepare("INSERT INTO meta(key, value) VALUES (?, ?)").run("tx-test", "2");
  db.exec("COMMIT");
  assert.equal(db.prepare("SELECT value FROM meta WHERE key = ?").get("tx-test").value, "2");
  assert.equal(db.prepare("INSERT OR IGNORE INTO meta(key, value) VALUES ('tx-test', ?)").run("3").changes, 0);
  assert.equal(db.prepare("SELECT value FROM meta WHERE key = ?").get("tx-test").value, "2");
});

test("dziennik zmian jest tylko do dopisywania (UPDATE / DELETE / TRUNCATE odrzucone)", { skip }, () => {
  db.prepare("INSERT INTO journal(ts, user_id, user_login, cmd, args, rev_before, rev_after, state_sha, prev_hash, hash) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)").run("t", null, null, "x", "{}", null, 1, "s", "0", "h-unit-1");
  assert.throws(() => db.exec("UPDATE journal SET cmd = 'zmienione'"), /append-only/);
  assert.throws(() => db.exec("DELETE FROM journal"), /append-only/);
  assert.throws(() => db.exec("TRUNCATE journal"), /append-only/);
  assert.equal(db.prepare("SELECT cmd FROM journal WHERE hash = ?").get("h-unit-1").cmd, "x");
});

test("błąd polecenia nie zrywa połączenia; tekst ze znakiem NUL zapisywany do znaku NUL (jak czyta go SQLite)", { skip }, () => {
  assert.throws(() => db.exec("SELECT * FROM nie_ma_takiej_tabeli"), e => e.name === "PgError" && e.code === "42P01" && !e.connectionLost);
  db.prepare("INSERT INTO meta(key, value) VALUES (?, ?)").run("nul", "a\u0000b");
  assert.equal(db.prepare("SELECT value FROM meta WHERE key = ?").get("nul").value, "a");
  const lite = new DatabaseSync(":memory:"); lite.exec("CREATE TABLE m(v TEXT)"); lite.prepare("INSERT INTO m VALUES (?)").run("a\u0000b");
  assert.equal(lite.prepare("SELECT v FROM m").get().v, "a", "ta sama wartość widziana przez program na SQLite"); lite.close();
  assert.equal(db.prepare("SELECT 1 AS x").get().x, 1);
});

