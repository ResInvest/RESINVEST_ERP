  // persistence after reload
  await page.reload(); await page.waitForTimeout(800);
  if (await page.$('text=Kto pracuje')) await page.click('button:has-text("Rozpocznij pracę")');
  await page.goto(FILE + '#/zamowienia'); await page.waitForTimeout(600);
  console.log('rows after reload:', await page.locator('.grid-table tbody tr').count());
  await page.screenshot({ path: `${S}/h/06-register.png` });
  for (const p of ['raporty', 'historia', 'slowniki', 'kontrahenci', 'ustawienia']) { await page.goto(FILE + '#/' + p); await page.waitForTimeout(500); await page.screenshot({ path: `${S}/h/07-${p}.png` }); }
  await page.keyboard.press('Control+k'); await page.keyboard.type('dreno'); await page.waitForTimeout(200);
  await page.screenshot({ path: `${S}/h/08-palette.png` }); await page.keyboard.press('Escape');
