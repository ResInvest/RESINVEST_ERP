  await page.screenshot({ path: `${S}/h/04-za-editor.png` });
  dl = page.waitForEvent('download');
  await page.click('button:has-text("Zapisz i wystaw")');
  d = await dl; console.log('za download:', d.suggestedFilename()); await d.saveAs(`${S}/h/za.pdf`);
  await page.waitForSelector('h1:has-text("ZAM/")');
  dl = page.waitForEvent('download'); await page.click('button[title="Pobierz DOCX"]'); d = await dl; await d.saveAs(`${S}/h/za.docx`);
  await page.screenshot({ path: `${S}/h/05-za-detail.png`, fullPage: true });
