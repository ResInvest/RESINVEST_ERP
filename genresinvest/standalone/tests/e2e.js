  const m = await browser.newContext({ ...devices['iPhone 13'], acceptDownloads: true });
  const mp = await m.newPage(); mp.on('pageerror', (e) => errors.push('MOBILE ' + e.message));
  await mp.goto(FILE); await mp.click('button:has-text("Rozpocznij pracę")'); await mp.waitForTimeout(500);
  await mp.screenshot({ path: `${S}/h/09-m-dash.png` });
  await mp.goto(FILE + '#/zamowienia/nowe'); await mp.waitForTimeout(700);
  await mp.screenshot({ path: `${S}/h/10-m-form.png` });
  await mp.click('.seg button:nth-child(2)'); await mp.waitForTimeout(400);
